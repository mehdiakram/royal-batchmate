/**
 * ===================================================================
 * Total Members Count Shortcode
 * Usage: [batchmate_members]
 * ===================================================================
 */
function BatchMate_total_members_shortcode() {
    global $wpdb;
    $member_table = $wpdb->prefix . 'batchmate_member';

    // ??????? ???? ??? ??????? ?????? ???? ???
    $count = $wpdb->get_var( "SELECT COUNT(id) FROM $member_table" );

    // ???????? ????????? ???????? ??????? ??? (????: 1,000)
    return number_format_i18n( $count );
}
add_shortcode( 'batchmate_members', 'BatchMate_total_members_shortcode' );